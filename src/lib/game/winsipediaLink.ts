/**
 * ESPN FBS/FCS team ids permanently excluded from `SLUGS` — confirmed against
 * winsipedia.com as never going to have a page (e.g. the program dropped
 * football, or ESPN mis-tags it into a division it doesn't actually play in),
 * as opposed to a team that's simply not added yet. Kept separate from
 * `SLUGS` so `scripts/check-winsipedia-slugs.ts` can tell "confirmed
 * permanent gap" apart from "needs a slug added". Empty for now .
 */
export const EXCLUDED_TEAM_IDS: Record<string, string> = {};

/** Link to the two teams' all-time head-to-head page, or `undefined` if neither team is covered by Winsipedia (FBS/FCS only — no D2/D3). */
export function winsipediaLink(game: Game): string | undefined {
	const away = SLUGS[game.away.id];
	const home = SLUGS[game.home.id];
	if (!away || !home) return undefined;
	return `https://www.winsipedia.com/${away}/vs/${home}`;
}
